#!/usr/bin/env python3
"""
build-alert-paste.py - regenerate windows/alerts/bt-deploy-PASTE.txt from the four alert scripts.

The paste block is what you copy into an Admin PowerShell window on a box that has no repo
(RDP clipboard / console). It writes each script into C:\\bt with a PowerShell here-string,
then runs bt-alerts.ps1 -Install. NEVER edit the paste block by hand: edit the .ps1 files,
then run:   python3 tools/build-alert-paste.py

Checks it enforces (a violation would break the paste on the box):
  - no line may start with '@  (it would end the here-string early)
  - ASCII only (Set-Content -Encoding ASCII would mangle anything else)
Output uses CRLF line endings.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]   # dev/tools/ -> repo root
SRC = ROOT / "windows" / "alerts"
OUT = SRC / "bt-deploy-PASTE.txt"
FILES = ["bt-alerts.ps1", "whoshere.ps1", "pii-hunt.ps1", "bt-selftest.ps1"]


def main() -> int:
    out = [
        "# ===== BLUE TEAM LIVE ALERTS: paste this whole block into an ADMIN PowerShell window =====",
        "# Generated by tools/build-alert-paste.py from windows/alerts/*.ps1. Do not edit by hand.",
        "# Writes C:\\bt\\bt-alerts.ps1, whoshere.ps1, pii-hunt.ps1, bt-selftest.ps1, then installs the alerts.",
        "New-Item C:\\bt -ItemType Directory -Force | Out-Null",
        "",
    ]
    bad = False
    for name in FILES:
        text = (SRC / name).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        for i, line in enumerate(text.split("\n"), 1):
            if line.startswith("'@"):
                print(f"ERROR {name}:{i} starts with '@ (would end the here-string)"); bad = True
            if any(ord(c) > 127 for c in line):
                print(f"ERROR {name}:{i} has a non-ASCII character"); bad = True
        out += ["@'", text, f"'@ | Set-Content C:\\bt\\{name} -Encoding ASCII", ""]
    if bad:
        return 1
    out += [
        "Set-ExecutionPolicy Bypass -Scope Process -Force",
        "Set-Location C:\\bt",
        'Write-Host "`nFiles written to C:\\bt. Installing alerts...`n" -ForegroundColor Cyan',
        ".\\bt-alerts.ps1 -Install",
        '$host.UI.RawUI.WindowTitle = "Admin PowerShell (not the alert window)"',
        'Write-Host "`nOptional check: C:\\bt\\bt-selftest.ps1" -ForegroundColor Cyan',
    ]
    OUT.write_bytes(("\r\n".join(out) + "\r\n").encode("ascii"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} blocks, {OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
